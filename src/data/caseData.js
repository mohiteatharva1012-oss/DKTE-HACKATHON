// Date calculation helpers for conspiracy network & PCB sync
export function parseLocalDate(dateInput) {
  if (!dateInput) return new Date(2026, 8, 29);
  if (typeof dateInput === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(dateInput.trim())) {
    const parts = dateInput.trim().split('-').map(Number);
    return new Date(parts[0], parts[1] - 1, parts[2]);
  }
  const d = new Date(dateInput);
  return isNaN(d.getTime()) ? new Date(2026, 8, 29) : d;
}

export function formatCaseDate(dateInput) {
  const d = parseLocalDate(dateInput);
  const day = String(d.getDate()).padStart(2, '0');
  const month = d.toLocaleString('en-US', { month: 'short' }).toUpperCase();
  const year = d.getFullYear();
  return `${day}-${month}-${year}`;
}

export function formatFriendlyDate(dateInput) {
  const d = parseLocalDate(dateInput);
  const day = d.getDate();
  const month = d.toLocaleString('en-US', { month: 'short' });
  const year = d.getFullYear();
  return `${day} ${month} ${year}`;
}

export function getTomorrowFriendlyDate(dateInput) {
  const d = parseLocalDate(dateInput);
  const nextDay = new Date(d.getFullYear(), d.getMonth(), d.getDate() + 1);
  const day = nextDay.getDate();
  const month = nextDay.toLocaleString('en-US', { month: 'short' });
  const year = nextDay.getFullYear();
  return `${day} ${month} ${year}`;
}

